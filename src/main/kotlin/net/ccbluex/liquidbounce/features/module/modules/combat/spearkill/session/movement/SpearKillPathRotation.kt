/**
 * Creates an unsmoothed route-owned rotation. Packet movement controls its own velocity, so local
 * movement correction must remain disabled while the server look follows each kinetic edge.
 */
internal fun spearKillRouteRotationTarget(rotation: Rotation) = RotationTarget(
    rotation = rotation,
    processors = emptyList(),
    ticksUntilReset = 1,
    resetThreshold = 180f,
    considerInventory = false,
    movementCorrection = MovementCorrection.OFF,
)
