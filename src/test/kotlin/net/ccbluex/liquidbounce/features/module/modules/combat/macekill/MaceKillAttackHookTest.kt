import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class MaceKillAttackHookTest {

    @Test
    fun `attack without an installed mace handler is not applied`() {
        val commit = MaceKillAcceptedAttackCommit<Any, Any>()
        val player = Any()
        val target = Any()

        assertEquals(MaceKillAttackResult.NOT_APPLIED, commit.commit(player, target))
    }

    @Test
    fun `one accepted attack commit applies its installed handler once`() {
        val commit = MaceKillAcceptedAttackCommit<Any, Any>()
        val player = Any()
        val target = Any()
        var applications = 0
        commit.install { receivedPlayer, receivedTarget ->
            assertTrue(receivedPlayer === player)
            assertTrue(receivedTarget === target)
            applications++
            MaceKillAttackResult.APPLIED
        }

        val result = commit.commit(player, target)

        assertEquals(MaceKillAttackResult.APPLIED, result)
        assertEquals(1, applications)
    }

    @Test
    fun `rejected accepted hook prevents the attack while other outcomes allow it`() {
        assertFalse(MaceKillAttackResult.REJECTED.allowsAttack)
        assertTrue(MaceKillAttackResult.APPLIED.allowsAttack)
        assertTrue(MaceKillAttackResult.NOT_APPLIED.allowsAttack)
    }

    @Test
    fun `a second handler cannot replace the module attack owner`() {
        val commit = MaceKillAcceptedAttackCommit<Any, Any>()
        commit.install { _, _ -> MaceKillAttackResult.APPLIED }

        assertThrows(IllegalStateException::class.java) {
            commit.install { _, _ -> MaceKillAttackResult.NOT_APPLIED }
        }
    }

}
